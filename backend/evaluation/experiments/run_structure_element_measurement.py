def _mean(values) -> float | None:
    seq = [float(v) for v in values if v is not None]
    if not seq:
        return None
    return _r(sum(seq) / len(seq))


def _median(values) -> float | None:
    seq = sorted(float(v) for v in values if v is not None)
    if not seq:
        return None
    mid = len(seq) // 2
    if len(seq) % 2:
        return _r(seq[mid])
    return _r((seq[mid - 1] + seq[mid]) / 2)


def retrieval_aggregates(traces: list[dict]) -> dict:
    """Retrieval metrics over one population, three gold views.

    The metric *definitions* are the project's existing ones
    (``evaluation.retrieval_metrics``) applied unchanged; only the retrieved
    list / gold set wiring differs per view:

    * ``evidence_unit`` (primary) — retrieved = final top-k (every retrieval
      unit, elements included); gold = every ingested unit whose text contains
      the question's gold evidence substring (one rule for both unit types).
    * ``chunk_only`` (legacy comparability) — retrieved = the chunk units in
      final top-k; gold = gold chunks (the ablation convention).
    * ``authored_gold`` — retrieved = final top-k; gold = gold chunks plus the
      authored gold elements that resolve to a persisted element (nulls
      excluded; see ``gold_structure_element_ids_if_available``).
    """
    views = {"evidence_unit": [], "chunk_only": [], "authored_gold": []}
    coverage = []
    for t in traces:
        top_k = t["final_top_k"]
        chunk_view = [cid for cid in top_k if not str(cid).startswith("structure:")]
        resolved_elements = [
            f"structure:{g['persisted_id']}"
            for g in t["gold_structure_element_ids_if_available"]
            if g["persisted_id"]
        ]
        gold_by_view = {
            "evidence_unit": t["gold_unit_ids"],
            "chunk_only": t["gold_evidence_ids"],
            "authored_gold": list(
                dict.fromkeys([*t["gold_evidence_ids"], *resolved_elements])
            ),
        }
        retrieved_by_view = {
            "evidence_unit": top_k,
            "chunk_only": chunk_view,
            "authored_gold": top_k,
        }
        for view in views:
            gold = gold_by_view[view]
            if not gold:
                continue  # no gold → nothing to score; kept out of the mean
            retrieved = retrieved_by_view[view]
            views[view].append(
                {
                    f"recall@{TOP_K}": retrieval_metrics.recall_at_k(
                        retrieved, gold, TOP_K
                    ),
                    f"precision@{TOP_K}": retrieval_metrics.precision_at_k(
                        retrieved, gold, TOP_K
                    ),
                    "mrr": retrieval_metrics.reciprocal_rank(retrieved, gold),
                    f"ndcg@{TOP_K}": retrieval_metrics.ndcg_at_k(
                        retrieved, gold, TOP_K
                    ),
                }
            )
        coverage.append(
            qa_metrics.evidence_coverage(t["qa_supplied_evidence_ids"], top_k)
        )

    out = {}
    for view, rows in views.items():
        out[view] = {
            "n": len(rows),
            **{
                key: _mean([row[key] for row in rows])
                for key in (
                    f"recall@{TOP_K}",
                    f"precision@{TOP_K}",
                    "mrr",
                    f"ndcg@{TOP_K}",
                )
            },
        }
    out["evidence_coverage"] = _mean(coverage)
    out["evidence_coverage_n"] = len(coverage)
    return out


def answer_aggregates(traces: list[dict]) -> dict:
    results = [
        {
            "answerable": t["answerable"],
            "predicted": t["predicted_answer"],
            "expected": list(t["gold_answer_candidates"]),
            "factual_grounded": t["factual_grounded"],
            "insufficient_context": t["insufficient_context"],
        }
        for t in traces
    ]
    answerable = [r for r in results if r["answerable"]]
    out = {
        "n": len(results),
        "n_answerable": len(answerable),
        "exact_match_rate": _mean(
            [t["exact_match"] for t in traces if t["answerable"]]
        ),
        "token_f1": _mean([t["token_f1"] for t in traces if t["answerable"]]),
        "answer_accuracy": _r(qa_metrics.answer_accuracy(results)),
        "factual_grounding_rate": _r(qa_metrics.factual_grounding_rate(results)),
    }
    unanswerable = [r for r in results if not r["answerable"]]
    out["unsupported_answer_rate"] = (
        _r(qa_metrics.unsupported_answer_rate(results))
        if unanswerable
        else None
    )
    return out


FUNNEL_STAGES = (
    "questions",
    "questions_with_persisted_structure",
    "questions_with_structural_seed",
    "questions_with_structural_candidates",
    "questions_with_structural_candidate_rrf_contribution",
    "questions_with_structure_element_in_final_top_k",
    "questions_with_structure_element_supplied_to_qa",
    "questions_where_supplied_structure_overlaps_gold_evidence",
)


def funnel_for(traces: list[dict]) -> dict:
    counts = {stage: 0 for stage in FUNNEL_STAGES}
    for t in traces:
        counts["questions"] += 1
        if t["persisted_structure_element_ids"]:
            counts["questions_with_persisted_structure"] += 1
        if t["structural_seed_ids"]:
            counts["questions_with_structural_seed"] += 1
        if t["structural_candidate_ids"]:
            counts["questions_with_structural_candidates"] += 1
        if any(
            (c or 0.0) > 0.0 for c in t["structural_candidate_rrf_contribution"]
        ):
            counts[
                "questions_with_structural_candidate_rrf_contribution"
            ] += 1
        if t["structure_element_count_in_top_k"] > 0:
            counts["questions_with_structure_element_in_final_top_k"] += 1
        if t["structure_elements_supplied_to_qa"]:
            counts["questions_with_structure_element_supplied_to_qa"] += 1
        if t["supplied_structure_overlapping_gold_evidence"]:
            counts[
                "questions_where_supplied_structure_overlaps_gold_evidence"
            ] += 1

    n = counts["questions"]
    rates = {
        stage: _r(counts[stage] / n) if n else None for stage in FUNNEL_STAGES
    }
    previous = None
    step_rates = {}
    for stage in FUNNEL_STAGES:
        if previous is not None:
            step_rates[stage] = (
                _r(counts[stage] / counts[previous])
                if counts[previous]
                else None
            )
        previous = stage
    return {"counts": counts, "rates": rates, "step_rates": step_rates}


def best_gold_rank(trace: dict) -> int | None:
    gold = set(trace["gold_unit_ids"])
    for rank, chunk_id in enumerate(trace["final_top_k"], start=1):
        if chunk_id in gold:
            return rank
    return None


def ranking_effects(control: dict, treatment: dict) -> dict:
    c_top = control["final_top_k"]
    t_top = treatment["final_top_k"]
    c_set, t_set = set(c_top), set(t_top)

    c_gold_rank = best_gold_rank(control)
    t_gold_rank = best_gold_rank(treatment)

    gold_entered = sorted(
        (t_set & set(treatment["gold_unit_ids"]))
        - (c_set & set(treatment["gold_unit_ids"]))
    )
    gold_left = sorted(
        (c_set & set(control["gold_unit_ids"]))
        - (t_set & set(control["gold_unit_ids"]))
    )

    delta = None
    if c_gold_rank is not None and t_gold_rank is not None:
        delta = t_gold_rank - c_gold_rank

    if c_gold_rank is None and t_gold_rank is not None:
        classification = "beneficial"
    elif c_gold_rank is not None and t_gold_rank is None:
        classification = "harmful"
    elif delta is not None and delta < 0:
        classification = "beneficial"
    elif delta is not None and delta > 0:
        classification = "harmful"
    else:
        classification = "neutral"

    return {
        "question_id": treatment["question_id"],
        "top_k_changed": c_set != t_set,
        "rank_order_changed": c_top != t_top,
        "gold_entered_top_k": gold_entered,
        "gold_left_top_k": gold_left,
        "gold_rank_control": c_gold_rank,
        "gold_rank_treatment": t_gold_rank,
        "gold_rank_delta": delta,
        "semantic_candidate_displaced": sorted(c_set - t_set),
        "structure_candidate_added": sorted(
            cid for cid in (t_set - c_set) if str(cid).startswith("structure:")
        ),
        "change_classification": classification,
    }


def aggregate_ranking_effects(effects: list[dict]) -> dict:
    n = len(effects)
    if not n:
        return {"n": 0}
    deltas = [e["gold_rank_delta"] for e in effects]
    return {
        "n": n,
        "top_k_changed_rate": _r(
            sum(1 for e in effects if e["top_k_changed"]) / n
        ),
        "rank_order_changed_rate": _r(
            sum(1 for e in effects if e["rank_order_changed"]) / n
        ),
        "gold_entered_rate": _r(
            sum(1 for e in effects if e["gold_entered_top_k"]) / n
        ),
        "gold_left_rate": _r(
            sum(1 for e in effects if e["gold_left_top_k"]) / n
        ),
        "gold_rank_delta_mean": _mean(deltas),
        "gold_rank_delta_median": _median(deltas),
        "beneficial": sum(
            1 for e in effects if e["change_classification"] == "beneficial"
        ),
        "harmful": sum(
            1 for e in effects if e["change_classification"] == "harmful"
        ),
        "neutral": sum(
            1 for e in effects if e["change_classification"] == "neutral"
        ),
    }


def answer_transitions(control: list[dict], treatment: list[dict]) -> dict:
    """Correctness transitions on answerable questions.

    ``correct`` is ``token_f1 >= 0.5`` against any acceptable answer — the same
    threshold the project's ``answer_accuracy`` uses.
    """
    t_by_id = {t["question_id"]: t for t in treatment}
    counts = {
        "wrong_to_correct": 0,
        "correct_to_wrong": 0,
        "correct_to_correct": 0,
        "wrong_to_wrong": 0,
    }
    details = []
    for c in control:
        if not c["answerable"]:
            continue
        t = t_by_id.get(c["question_id"])
        if t is None:
            continue
        c_ok = c["token_f1"] is not None and c["token_f1"] >= 0.5
        t_ok = t["token_f1"] is not None and t["token_f1"] >= 0.5
        if c_ok and t_ok:
            counts["correct_to_correct"] += 1
        elif c_ok and not t_ok:
            counts["correct_to_wrong"] += 1
        elif not c_ok and t_ok:
            counts["wrong_to_correct"] += 1
        else:
            counts["wrong_to_wrong"] += 1
        if c_ok != t_ok or c["predicted_answer"] != t["predicted_answer"]:
            details.append(
                {
                    "question_id": c["question_id"],
                    "control_answer": c["predicted_answer"],
                    "treatment_answer": t["predicted_answer"],
                    "control_token_f1": c["token_f1"],
                    "treatment_token_f1": t["token_f1"],
                    "transition": (
                        "wrong_to_correct"
                        if not c_ok and t_ok
                        else "correct_to_wrong"
                        if c_ok and not t_ok
                        else "correct_to_correct"
                        if c_ok
                        else "wrong_to_wrong"
                    ),
                }
            )
    return {"counts": counts, "changed_or_flipped": details}


def saturation_analysis(traces: list[dict]) -> dict:
    records = []
    for t in traces:
        saturated = (
            t["semantic_candidate_count"] >= TOP_K
            and t["structural_candidate_count"] > 0
        )
        element_only = [
            cid
            for cid in t["structural_candidate_ids"]
            if cid not in set(t["semantic_candidate_ids"])
        ]
        records.append(
            {
                "question_id": t["question_id"],
                "answerable": t["answerable"],
                "category": t["category"],
                "discrimination_label": t["discrimination_label"],
                "semantic_candidate_count": t["semantic_candidate_count"],
                "structural_candidate_count": t["structural_candidate_count"],
                "element_only_candidate_count": len(element_only),
                "semantic_saturated": t["semantic_candidate_count"] >= TOP_K,
                "structural_only_admitted": bool(
                    t["structural_only_ids_in_top_k"]
                ),
                "element_only_admitted": any(
                    str(cid).startswith("structure:")
                    for cid in t["structural_only_ids_in_top_k"]
                ),
                "structural_admission_mathematically_possible": t[
                    "structural_admission_mathematically_possible"
                ],
                "highest_structural_only_contribution": t[
                    "highest_structural_only_contribution"
                ],
                "lowest_fusion_score_in_top_k": t[
                    "lowest_fusion_score_in_top_k"
                ],
                "lowest_semantic_contribution_in_top_k": t[
                    "lowest_semantic_contribution_in_top_k"
                ],
            }
        )

    eligible = [
        r
        for r in records
        if r["semantic_saturated"] and r["structural_candidate_count"] > 0
    ]
    admitted = [r for r in eligible if r["structural_only_admitted"]]
    element_admitted = [r for r in eligible if r["element_only_admitted"]]

    def _pop(pop_filter):
        sub = [r for r in eligible if pop_filter(r)]
        return {
            "n": len(sub),
            "structural_only_admission_count": sum(
                1 for r in sub if r["structural_only_admitted"]
            ),
            "structural_only_admission_rate": (
                _r(
                    sum(1 for r in sub if r["structural_only_admitted"])
                    / len(sub)
                )
                if sub
                else None
            ),
            "element_only_admission_count": sum(
                1 for r in sub if r["element_only_admitted"]
            ),
            "element_only_admission_rate": (
                _r(
                    sum(1 for r in sub if r["element_only_admitted"]) / len(sub)
                )
                if sub
                else None
            ),
            "admission_possible_count": sum(
                1
                for r in sub
                if r["structural_admission_mathematically_possible"]
            ),
        }

    return {
        "definition": (
            "eligible = questions where semantic_candidate_count >= top_k and "
            "structural_candidate_count > 0; admission rate = share of eligible "
            "questions where a structural-only candidate appears in the final "
            "top-k under the production RRF (0.70/0.30, k=60)"
        ),
        "per_question": records,
        "overall": _pop(lambda r: True),
        "answerable": _pop(lambda r: r["answerable"]),
        "DISCRIMINATING_answerable": _pop(
            lambda r: r["answerable"]
            and r["discrimination_label"] == "DISCRIMINATING"
        ),
        "admitted_question_ids": sorted(
            r["question_id"] for r in admitted
        ),
        "element_admitted_question_ids": sorted(
            r["question_id"] for r in element_admitted
        ),
    }


def metric_delta(control: dict, treatment: dict) -> dict:
    out = {}
    for key in sorted(set(control) | set(treatment)):
        c_val, t_val = control.get(key), treatment.get(key)
        if isinstance(c_val, (int, float)) and isinstance(t_val, (int, float)):
            out[key] = _r(float(t_val) - float(c_val))
        else:
            out[key] = None
    return out


def build_analysis(
    control_traces: list[dict],
    treatment_traces: list[dict],
) -> dict:
    c_by_id = {t["question_id"]: t for t in control_traces}
    t_by_id = {t["question_id"]: t for t in treatment_traces}
    shared = [qid for qid in c_by_id if qid in t_by_id]

    populations: dict[str, dict] = {}
    for population in POPULATIONS:
        qids = {
            qid
            for qid in shared
            if population_of(t_by_id[qid], population)
        }
        c_sub = [c_by_id[qid] for qid in sorted(qids)]
        t_sub = [t_by_id[qid] for qid in sorted(qids)]

        effects = [
            ranking_effects(c_by_id[qid], t_by_id[qid]) for qid in sorted(qids)
        ]
        populations[population] = {
            "n": len(qids),
            "funnel_treatment": funnel_for(t_sub),
            "funnel_control": funnel_for(c_sub),
            "ranking_effects": aggregate_ranking_effects(effects),
            "ranking_effect_details": effects,
            "retrieval_metrics": {
                "CONTROL": retrieval_aggregates(c_sub),
                "TREATMENT": retrieval_aggregates(t_sub),
                "DELTA": {
                    view: metric_delta(
                        retrieval_aggregates(c_sub).get(view, {})
                        if isinstance(retrieval_aggregates(c_sub).get(view), dict)
                        else {},
                        retrieval_aggregates(t_sub).get(view, {})
                        if isinstance(retrieval_aggregates(t_sub).get(view), dict)
                        else {},
                    )
                    for view in ("evidence_unit", "chunk_only", "authored_gold")
                },
            },
            "answer_metrics": {
                "CONTROL": answer_aggregates(c_sub),
                "TREATMENT": answer_aggregates(t_sub),
            },
            "answer_transitions": answer_transitions(c_sub, t_sub),
        }
        populations[population]["answer_metrics"]["DELTA"] = metric_delta(
            populations[population]["answer_metrics"]["CONTROL"],
            populations[population]["answer_metrics"]["TREATMENT"],
        )

    categories = sorted({t["category"] for t in treatment_traces if t["category"]})
    category_analysis: dict[str, dict] = {}
    for category in categories:
        c_sub = [t for t in control_traces if t["category"] == category]
        t_sub = [t for t in treatment_traces if t["category"] == category]
        t_ids = {t["question_id"] for t in t_sub}
        effects = [
            ranking_effects(c_by_id[qid], t_by_id[qid])
            for qid in sorted(t_ids)
            if qid in c_by_id
        ]
        category_analysis[category] = {
            "n": len(t_sub),
            "n_answerable": sum(1 for t in t_sub if t["answerable"]),
            "funnel_treatment": funnel_for(t_sub),
            "top_k_change_rate": aggregate_ranking_effects(effects).get(
                "top_k_changed_rate"
            ),
            "rank_order_change_rate": aggregate_ranking_effects(effects).get(
                "rank_order_changed_rate"
            ),
            "gold_rank_delta_mean": aggregate_ranking_effects(effects).get(
                "gold_rank_delta_mean"
            ),
            "gold_rank_delta_median": aggregate_ranking_effects(effects).get(
                "gold_rank_delta_median"
            ),
            "beneficial_harmful_neutral": {
                key: aggregate_ranking_effects(effects).get(key)
                for key in ("beneficial", "harmful", "neutral")
            },
            "retrieval_metrics": {
                "CONTROL": retrieval_aggregates(c_sub),
                "TREATMENT": retrieval_aggregates(t_sub),
            },
            "answer_metrics": {
                "CONTROL": answer_aggregates(c_sub),
                "TREATMENT": answer_aggregates(t_sub),
            },
            "answer_transitions": answer_transitions(c_sub, t_sub),
        }
        category_analysis[category]["retrieval_metrics"]["DELTA"] = {
            view: metric_delta(
                category_analysis[category]["retrieval_metrics"]["CONTROL"].get(
                    view, {}
                )
                if isinstance(
                    category_analysis[category]["retrieval_metrics"]["CONTROL"].get(
                        view
                    ),
                    dict,
                )
                else {},
                category_analysis[category]["retrieval_metrics"][
                    "TREATMENT"
                ].get(view, {})
                if isinstance(
                    category_analysis[category]["retrieval_metrics"][
                        "TREATMENT"
                    ].get(view),
                    dict,
                )
                else {},
            )
            for view in ("evidence_unit", "chunk_only", "authored_gold")
        }
        category_analysis[category]["answer_metrics"]["DELTA"] = metric_delta(
            category_analysis[category]["answer_metrics"]["CONTROL"],
            category_analysis[category]["answer_metrics"]["TREATMENT"],
        )

    saturation = saturation_analysis(treatment_traces)

    return {
        "populations": populations,
        "category_analysis": category_analysis,
        "structural_saturation": saturation,
    }


def decide(analysis: dict) -> dict:
    """Apply the pre-declared decision rules to the measured primary population.

    The rules are applied to measurements only; the recommendation is never
    chosen in advance:

    * A — element candidates reach top-k (admission > 0) and produce credible
      positive retrieval and/or answer evidence without unacceptable
      regressions;
    * B — elements reach candidates/QA but the 0.70/0.30 fusion prevents
      useful admission or ranking influence (admission == 0 or admission
      mathematically impossible);
    * C — candidate generation/quality is the problem: no structural candidates
      are produced at all, or candidates are admitted but net-harmful;
    * D — the path is reachable, sufficiently admitted and correctly measured,
      yet shows no meaningful retrieval/answer advantage.
    """
    primary = analysis["populations"]["DISCRIMINATING_answerable"]
    funnel = primary["funnel_treatment"]["counts"]
    ranking = primary["ranking_effects"]
    saturation = analysis["structural_saturation"]["DISCRIMINATING_answerable"]

    candidates = funnel["questions_with_structural_candidates"]
    admission_count = funnel[
        "questions_with_structure_element_in_final_top_k"
    ]
    admission_rate = primary["funnel_treatment"]["rates"][
        "questions_with_structure_element_in_final_top_k"
    ]
    retrieval_delta = (
        primary["retrieval_metrics"]["DELTA"]
        .get("evidence_unit", {})
        .get("mrr")
    )
    answer_delta = primary["answer_metrics"]["DELTA"].get("token_f1")
    beneficial = ranking.get("beneficial", 0)
    harmful = ranking.get("harmful", 0)

    evidence = {
        "primary_population": "DISCRIMINATING_answerable",
        "structural_candidate_questions": candidates,
        "element_top_k_admission_count": admission_count,
        "element_top_k_admission_rate": admission_rate,
        "admission_mathematically_possible_count": saturation[
            "admission_possible_count"
        ],
        "retrieval_mrr_delta_evidence_unit": retrieval_delta,
        "answer_token_f1_delta": answer_delta,
        "beneficial_changes": beneficial,
        "harmful_changes": harmful,
    }

    if candidates == 0:
        return {
            "recommendation": (
                "FIX STRUCTURAL CANDIDATE QUALITY BEFORE FULL A/B/C/D"
            ),
            "evidence": evidence,
        }
    if admission_count > 0 and (
        (retrieval_delta or 0.0) > 0.0
        or ((answer_delta or 0.0) > 0.0 and beneficial > harmful)
    ) and harmful <= beneficial:
        return {
            "recommendation": (
                "PROCEED TO FULL A/B/C/D — ELEMENT PATH SHOWS MEASURABLE BENEFIT"
            ),
            "evidence": evidence,
        }
    if admission_count > 0 and (
        harmful > beneficial
        or (retrieval_delta or 0.0) < 0.0
        or (answer_delta or 0.0) < 0.0
    ):
        return {
            "recommendation": (
                "FIX STRUCTURAL CANDIDATE QUALITY BEFORE FULL A/B/C/D"
            ),
            "evidence": evidence,
        }
    if admission_count == 0:
        return {
            "recommendation": (
                "CALIBRATE STRUCTURAL RANKING BEFORE FULL A/B/C/D"
            ),
            "evidence": evidence,
        }
    return {
        "recommendation": (
            "STRUCTURAL ELEMENT PATH SHOWS NO BENEFIT — RETAIN NULL RESULT"
        ),
        "evidence": evidence,
    }


