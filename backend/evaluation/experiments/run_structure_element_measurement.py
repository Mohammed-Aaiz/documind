def _first_difference(a, b, path: str = "$") -> str | None:
    """First structural/value difference between two payloads (for diagnostics)."""
    if type(a) is not type(b):
        return f"{path}: type {type(a).__name__} vs {type(b).__name__}"
    if isinstance(a, dict):
        for key in sorted(set(a) | set(b)):
            if key not in a:
                return f"{path}.{key}: missing in run 1"
            if key not in b:
                return f"{path}.{key}: missing in run 2"
            found = _first_difference(a[key], b[key], f"{path}.{key}")
            if found:
                return found
        return None
    if isinstance(a, list):
        if len(a) != len(b):
            return f"{path}: length {len(a)} vs {len(b)}"
        for index, (left, right) in enumerate(zip(a, b)):
            found = _first_difference(left, right, f"{path}[{index}]")
            if found:
                return found
        return None
    if a != b:
        return f"{path}: {a!r} vs {b!r}"
    return None


