_DET_NAMESPACE = uuid.UUID("6f1c6ba7-5b67-4f5e-9f5c-0d5a2a9c0d1e")


class DeterministicUUIDs:
    """Counter-seeded ``uuid5`` stand-in for ``uuid.uuid4``.

    Every ingested row id in this experiment is generated through call-time
    ``uuid.uuid4()`` lookups, so swapping the module attribute makes row ids a
    deterministic function of generation order.  Ids are opaque identity tokens;
    this removes run-to-run metadata noise so results can be compared
    byte-for-byte.  ORM column defaults captured at import time are never
    triggered because the harness sets every primary key explicitly.
    """

    def __init__(self, run_seed: str):
        self.run_seed = run_seed
        self.count = 0

    def __call__(self) -> uuid.UUID:
        self.count += 1
        return uuid.uuid5(_DET_NAMESPACE, f"{self.run_seed}:{self.count}")

    def __enter__(self):
        self._real = uuid.uuid4
        uuid.uuid4 = self
        return self

    def __exit__(self, *exc):
        uuid.uuid4 = self._real
        return False


