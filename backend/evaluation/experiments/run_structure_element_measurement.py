def population_of(trace: dict, population: str) -> bool:
    answerable = trace["answerable"]
    disc = trace["discrimination_label"]
    if population == "DISCRIMINATING_answerable":
        return answerable and disc == "DISCRIMINATING"
    if population == "WEAKLY_DISCRIMINATING_answerable":
        return answerable and disc == "WEAKLY_DISCRIMINATING"
    if population == "NOT_DISCRIMINATING_answerable":
        return answerable and disc == "NOT_DISCRIMINATING"
    if population == "all_answerable":
        return answerable
    if population == "unanswerable":
        return not answerable
    return True


def select_population(traces: list[dict], population: str) -> list[dict]:
    return [t for t in traces if population_of(t, population)]


