#!/usr/bin/env python3
"""Structure-element measurement — CONTROL vs TREATMENT on the unchanged corpus.

Research code.  Run explicitly from ``backend/``:

    ./venv/Scripts/python.exe evaluation/experiments/run_structure_element_measurement.py

What it measures
----------------
The verified structural-retrieval fix made persisted ``DocumentStructureElement``
rows first-class retrieval candidates that participate in the production RRF
ranking.  This experiment measures what that path actually contributes on the
existing ``structure_discriminating_v1`` corpus — nothing else.  The corpus,
the parser, the graph schema, the retrieval architecture, the RRF weights and
the QA model are all used exactly as they are.

Two configurations are measured over the same ingested corpus:

CONTROL
    Production behaviour with **only** the new persisted-element ranking
    contribution disabled (``chat.rag.retrieve_structural_element_candidates``
    returns ``[]`` for the arm).  Everything else is production, including the
    chunk-level structural path and the post-ranking
    ``brain.adapters._augment_with_structure`` element stream.

TREATMENT
    Current production element-ranked behaviour, exactly as implemented.

Honesty constraints
-------------------
* No score is invented: element candidates carry ``score=0.0`` (no similarity
  exists for an element) and the rank-based RRF contribution derived from the
  real candidate ordering.  ``null`` is stored wherever a field cannot be
  measured honestly (e.g. authored gold element ids with no resolvable
  persisted counterpart).
* The instrumented arithmetic is cross-checked: the captured semantic and
  structural streams are re-fused with the production ``chat.rag.fuse_dual_path``
  and must equal the production ``retrieve_dual_path`` output exactly, or the
  run aborts with a measurement-integrity error.  This experiment never
  silently changes production behaviour.

Determinism
-----------
The experiment is executed twice (two independent user/ingest/measure/teardown
cycles) and the machine-readable payloads must be byte-identical.  All runtime
metadata that could differ between runs is eliminated up front: no timestamps,
no latencies, and row ids are generated by a deterministic counter-seeded
``uuid5`` stand-in for ``uuid.uuid4`` during setup/ingestion (id *values* are
opaque identity tokens; generation order is a deterministic function of the
fixed corpus and code path).  Two other sources of run-to-run noise are
removed without touching production: the one-time embedding/QA model loads are
warmed *before* the deterministic-id region (the embedding model consumes real
``uuid4`` calls while loading), and the semantic stream is re-sorted by
``(-similarity, chunk_id)`` so chunks with exactly equal cosine similarity get
a fixed order instead of the production query's arbitrary one.  Both
normalisations are applied identically to both arms and change no evidence or
score.  Nothing else is excluded from the comparison.

Publication
-----------
The three published artifacts (``evaluation/reports/structure_element_measurement_control.json``,
``..._treatment.json``, ``..._analysis.json``) are evaluation evidence and are
written append-only through ``evaluation.artifacts.write_evidence``, which refuses
to replace an existing artifact rather than silently overwriting a recorded
result.  All three names are pre-flighted before the first byte is written, and
``--replace`` is the explicit, operator-supplied opt-in for a deliberate
re-publication.  ``--smoke`` output stays in a fresh temporary directory and is
not evidence.

Data safety
-----------
The run owns a single, dedicated user (``ablation_eval@test.local``).  All
setup and teardown deletes are scoped to that user id; the runner never issues
an unscoped ``DELETE`` and never touches another account's rows.
"""

