def derive_gold(
    question, meta_q, ingested: dict, persisted_elements: list[dict], corpus
) -> dict:
    """Gold evidence for one question, every mapping derived or ``null``.

    * ``gold_evidence_ids`` — chunk ids whose text contains the question's gold
      evidence substrings (the corpus's existing convention, produced upstream
      by ``run_dual_path_ablation.build_questions`` and re-derived here for the
      record).
    * ``gold_unit_ids`` — the same evidence-substring rule extended to every
      ingested retrieval unit (chunks *and* persisted elements).  This is the
      primary relevance definition: it applies one rule consistently to both
      retrieval unit types instead of structurally penalising element units.
    * ``gold_structure_element_ids_if_available`` — the corpus's *authored*
      gold element ids resolved against persisted elements by conservative
      deterministic matching (exact content match first, then unique
      type+page+path, then unique type+path).  ``null`` whenever no unique
      persisted counterpart exists — the authored corpus includes table
      row/cell gold that the parser deliberately does not persist, so those
      stay ``null`` rather than being guessed onto some element.
    """
    doc_name = next(
        (
            name
            for name, info in ingested.items()
            if info["document_id"] == str(question.document_id)
        ),
        None,
    )
    info = ingested.get(doc_name, {}) if doc_name else {}

    evidence = [e for e in (meta_q.evidence if meta_q else ()) if e]
    evidence_norm = [norm(e) for e in evidence]

    gold_chunks = list(question.gold_chunk_ids)

    gold_units = list(gold_chunks)
    for chunk_id, content in zip(info.get("chunk_ids", []), info.get("contents", [])):
        body = norm(content)
        if any(e and e in body for e in evidence_norm):
            if chunk_id not in gold_units:
                gold_units.append(chunk_id)

    doc_elements = [
        e
        for e in persisted_elements
        if e["document_id"] == str(question.document_id)
    ]
    for element in doc_elements:
        body = norm(element["content"])
        if any(e and e in body for e in evidence_norm):
            gold_units.append(f"structure:{element['element_id']}")

    # --- authored gold element ids → persisted ids (conservative) -----------
    authored_index = {e.element_id: e for e in corpus.elements}

    def _path_key(value) -> tuple[str, ...]:
        return tuple(norm(p) for p in (value or ()) if p)

    resolved: list[dict] = []
    for authored_id in (meta_q.gold_element_ids if meta_q else ()):
        authored = authored_index.get(authored_id)
        entry = {
            "authored_id": authored_id,
            "persisted_id": None,
            "match_rule": None,
        }
        if authored is None:
            entry["match_rule"] = "unresolved:not_in_corpus_index"
            resolved.append(entry)
            continue

        authored_path = _path_key(authored.heading_path)
        authored_content = norm(authored.content)

        def _candidates():
            for element in doc_elements:
                if element["element_type"] != authored.element_type:
                    continue
                yield element

        match = None
        rule = None

        if authored_content:
            exact = [
                e
                for e in _candidates()
                if norm(e["content"]) == authored_content
            ]
            if len(exact) == 1:
                match, rule = exact[0], "exact_content+type"
        if match is None:
            scoped = [
                e
                for e in _candidates()
                if e["page_number"] == authored.page_number
                and _path_key(e["heading_path"]) == authored_path
            ]
            if len(scoped) == 1:
                match, rule = scoped[0], "unique_type+page+heading_path"
        if match is None:
            scoped = [
                e
                for e in _candidates()
                if _path_key(e["heading_path"]) == authored_path
            ]
            if len(scoped) == 1:
                match, rule = scoped[0], "unique_type+heading_path"
        if match is None:
            entry["match_rule"] = "unresolved:no_unique_persisted_match"
        else:
            entry["persisted_id"] = match["element_id"]
            entry["match_rule"] = rule
        resolved.append(entry)

    return {
        "gold_evidence_ids": gold_chunks,
        "gold_unit_ids": gold_units,
        "gold_structure_element_ids": resolved,
    }


