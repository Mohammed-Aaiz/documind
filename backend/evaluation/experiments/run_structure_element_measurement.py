def _warm_models() -> None:
    """Force one-time lazy model loads *outside* the deterministic id region.

    The embedding model consumes three real ``uuid.uuid4`` calls while it
    loads (measured, not assumed).  If that load happened inside the first
    run's deterministic-id region it would shift every later generated id —
    and therefore every chunk-id tie-break in the fusion sorts — relative to
    the second, already-warm run, which is exactly the run-to-run diff that
    must not exist.  Warming the models first makes the id generation order a
    pure function of the fixed corpus and code path.
    """
    from chat.qa_model import answer_question
    from embeddings.model import embed_query, embed_texts

    embed_texts(["warmup"])
    embed_query("warmup")
    answer_question("warmup", "warmup")


