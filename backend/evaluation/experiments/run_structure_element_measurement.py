_EVALUATION_OPERATION = (
    "the structure-element measurement (it creates and deletes rows)"
)

#: The DSN the central guard approved.  Set only by guard_evaluation_target().
APPROVED_EVALUATION_DSN: str | None = None


def guard_evaluation_target() -> str:
    """Resolve the evaluation target and let the central guard approve it.

    A refusal raises before any database-dependent module is imported.  On
    approval the DSN is exported as DATABASE_URL, and the cached settings are
    dropped: storage.database reads settings once at import, so a cached
    application URL would otherwise override the approved target.
    """
    global APPROVED_EVALUATION_DSN
    application_dsn = application_database_url()
    evaluation_dsn = evaluation_database_url(application_url=application_dsn)
    identity = assert_safe_evaluation_target(
        evaluation_dsn,
        operation=_EVALUATION_OPERATION,
        application_url=application_dsn,
    )
    print(
        "[evaluation-db] application database : "
        f"{describe_identity(database_identity(application_dsn))}"
    )
    print(f"[evaluation-db] evaluation database  : {describe_identity(identity)}")
    # Validity (above) is not permission to destroy: the operator must also name this exact database.
    assert_disposal_authorized(
        evaluation_dsn,
        operation=_EVALUATION_OPERATION,
        application_url=application_dsn,
    )
    os.environ["DATABASE_URL"] = evaluation_dsn
    from config import get_settings  # noqa: E402

    # Drop any cached settings, then read the effective value storage will build
    # its engine from.  Settings() reads only the environment and backend/.env and
    # opens no database connection.  A mismatch refuses here, before storage is
    # imported, so no engine can be constructed from the other target.
    get_settings.cache_clear()
    effective = get_settings().database_url
    if effective != evaluation_dsn:
        raise RuntimeError(
            "the effective application settings name a different database than the "
            "approved evaluation target; refusing before any engine is built"
        )
    APPROVED_EVALUATION_DSN = evaluation_dsn
    return evaluation_dsn


def verify_bound_engine(db_engine) -> None:
    """Refuse to run unless the engine was built for the approved target."""
    from sqlalchemy.engine import make_url  # noqa: E402

    expected = make_url(APPROVED_EVALUATION_DSN)
    actual = db_engine.url
    if (actual.database, actual.host, actual.port) != (
        expected.database,
        expected.host,
        expected.port,
    ):
        raise RuntimeError(
            "the database engine was built for a different target than the one "
            "the isolation guard approved; refusing to run"
        )


def bind_database_runtime() -> None:
    """Bind the database-dependent names.  The guard runs first; idempotent."""
    global async_session, engine, rag
    if engine is not None:
        return
    guard_evaluation_target()
    from chat import rag as rag_module  # noqa: E402
    from storage.database import async_session as session_factory  # noqa: E402
    from storage.database import engine as db_engine  # noqa: E402

    verify_bound_engine(db_engine)
    rag = rag_module
    async_session = session_factory
    engine = db_engine


async def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    smoke = "--smoke" in argv
    # `--replace` deliberately re-publishes over recorded evidence.  It is never
    # implied: without it, existing artifacts are preserved and the run refuses.
    replace = "--replace" in argv
    bind_database_runtime()

    print("=" * 78)
    print("STRUCTURE-ELEMENT MEASUREMENT — CONTROL vs TREATMENT")
    print("  corpus: structure_discriminating_v1 (unchanged)")
    print("=" * 78)

    runs: list[dict] = []
    for index in range(1, RUNS + 1):
        print(f"\n--- run {index}/{RUNS} ---")
        # The same seed for both runs.  Row ids are opaque identity tokens, so
        # a fixed generation order must reproduce the same id values; using the
        # same seed makes the byte comparison test measurement determinism
        # rather than run-to-run id noise.
        runs.append(await run_once("structure-element-measurement"))
        if smoke and index == 1:
            break

    if smoke:
        out_dir = Path(tempfile.mkdtemp(prefix="structure-measurement-smoke-"))
        payload = runs[0]
        (out_dir / "control.json").write_text(
            canonical(payload["control"]), encoding="utf-8"
        )
        (out_dir / "treatment.json").write_text(
            canonical(payload["treatment"]), encoding="utf-8"
        )
        (out_dir / "analysis.json").write_text(
            canonical(payload["analysis"]), encoding="utf-8"
        )
        print(f"\nsmoke payloads written to {out_dir}")
        return 0

    # --- determinism: both runs must serialise byte-identically ------------
    determinism: dict = {"runs_compared": len(runs)}
    for name in ("control", "treatment", "analysis"):
        blobs = [canonical(run[name]).encode("utf-8") for run in runs]
        hashes = [hashlib.sha256(blob).hexdigest() for blob in blobs]
        determinism[name] = {
            "byte_identical": len(set(blobs)) == 1,
            "sha256_run1": hashes[0],
            "sha256_run2": hashes[1] if len(hashes) > 1 else None,
        }

    analysis_payload = dict(runs[0]["analysis"])
    analysis_payload["determinism"] = determinism
    analysis_payload["decision_gate"] = decide(runs[0]["analysis"])

    # The final analysis file is itself reproducible: run 2's core plus the
    # same determinism block must render identically.
    analysis_run2 = dict(runs[1]["analysis"])
    analysis_run2["determinism"] = determinism
    analysis_run2["decision_gate"] = decide(runs[1]["analysis"])
    determinism["analysis_final_byte_identical"] = (
        canonical(analysis_payload) == canonical(analysis_run2)
    )
    analysis_payload["determinism"] = determinism

    all_identical = all(
        determinism[name]["byte_identical"]
        for name in ("control", "treatment", "analysis")
    ) and determinism["analysis_final_byte_identical"]

    # --- publish: append-only unless the operator explicitly asks to replace ---
    # All three names are pre-flighted before the first byte is written, so a
    # collision leaves the previous evidence intact instead of producing a
    # partial artifact set.  The text written is exactly what the previous
    # revision wrote: only the write mechanism changed.
    outputs = {
        "structure_element_measurement_control.json": canonical(
            runs[0]["control"]
        ),
        "structure_element_measurement_treatment.json": canonical(
            runs[0]["treatment"]
        ),
        "structure_element_measurement_analysis.json": canonical(
            analysis_payload
        ),
    }
    targets = {filename: REPORTS_DIR / filename for filename in outputs}
    if not replace:
        collisions = [str(path) for path in targets.values() if path.exists()]
        if collisions:
            print(
                "\nREFUSING to publish: existing evaluation evidence would be "
                f"replaced: {', '.join(collisions)}",
                file=sys.stderr,
            )
            print(
                "Nothing was written; the recorded evidence is unchanged. "
                "Move or rename it, or re-run with --replace to deliberately "
                "re-publish over it.",
                file=sys.stderr,
            )
            return 2
    try:
        for filename, content in outputs.items():
            write_evidence(targets[filename], content, replace=replace)
            print(f"  wrote evaluation/reports/{filename}")
    except ArtifactExistsError as exc:
        print(f"\nREFUSING to publish: {exc}", file=sys.stderr)
        print(
            "A file appeared after the pre-flight check, so the artifact set is "
            "incomplete. Nothing further was written.",
            file=sys.stderr,
        )
        return 2

    print()
    primary = analysis_payload["populations"]["DISCRIMINATING_answerable"]
    funnel = primary["funnel_treatment"]
    print("PRIMARY POPULATION — DISCRIMINATING answerable")
    for stage in FUNNEL_STAGES:
        print(f"  {stage:<62} {funnel['counts'][stage]}")
    sat = analysis_payload["structural_saturation"][
        "DISCRIMINATING_answerable"
    ]
    print(
        "  structural-only top-k admission under saturation: "
        f"{sat['structural_only_admission_count']}/{sat['n']} "
        f"(element-only: {sat['element_only_admission_count']})"
    )
    print(
        f"  determinism (byte-identical): {all_identical}"
    )
    print(f"  DECISION GATE: {analysis_payload['decision_gate']['recommendation']}")

    if not all_identical:
        for name in ("control", "treatment", "analysis"):
            if not determinism[name]["byte_identical"]:
                print(
                    f"  first difference in {name}: "
                    f"{_first_difference(runs[0][name], runs[1][name])}",
                    file=sys.stderr,
                )
        print(
            "DETERMINISM FAILURE: runs differ — investigate before reporting "
            "conclusions.",
            file=sys.stderr,
        )
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
