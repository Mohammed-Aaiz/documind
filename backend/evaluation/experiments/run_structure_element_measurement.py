async def ingest_corpus(
    db: AsyncSession, user_id, corpus, chunker_version: str
) -> dict[str, dict]:
    """Ingest every corpus document exactly as production does.

    Mirrors ``run_dual_path_ablation.ingest_corpus`` (production chunk builder,
    ``parse_pdf`` + ``replace_document_structure``, ``replace_document_graph``,
    production embeddings) but additionally captures the parser's element ids
    and the *exact* parsed→persisted element map returned by
    ``replace_document_structure`` (``source_id -> ORM element``), so the
    measurement never fabricates that mapping.
    """
    from documents.models import Document
    from documents.parser import parse_pdf
    from documents.processing import extract_text
    from documents.routes import _build_chunk_objects, _chunk_views
    from documents.structure import replace_document_structure
    from embeddings.model import embed_texts
    from graph.service import replace_document_graph
    from storage.file_store import save_upload

    summary: dict[str, dict] = {}

    with tempfile.TemporaryDirectory() as tmp:
        directory = Path(tmp)
        for doc in corpus:
            path = doc.write(directory)
            file_bytes = path.read_bytes()
            contents_elements = extract_text(path, doc.file_type)

            document = Document(
                id=uuid.uuid4(),
                user_id=user_id,
                name=doc.name,
                file_type=doc.file_type,
                file_size=len(file_bytes),
                stored_path=str(save_upload(file_bytes, doc.name, str(user_id))),
                chunker_version=chunker_version,
                chunk_count=0,
                status="ready",
                embedding_status="processing",
            )
            db.add(document)
            await db.flush()

            chunk_objects = _build_chunk_objects(
                contents_elements, document.id, chunker_version, db
            )
            await db.flush()

            contents = [c.content for c in chunk_objects]
            embeddings = embed_texts(contents) if contents else []
            for index, obj in enumerate(chunk_objects):
                obj.embedding = embeddings[index] if index < len(embeddings) else None

            document.chunk_count = len(chunk_objects)
            document.embedding_status = "ready"
            await db.flush()

            parsed_elements: list[dict] = []
            parsed_to_persisted: dict[str, str] = {}
            if doc.file_type == "pdf":
                try:
                    parsed = parse_pdf(path)
                    by_source = await replace_document_structure(
                        db, document.id, parsed
                    )
                    for parsed_element in parsed.elements:
                        orm_element = by_source.get(parsed_element.source_id)
                        parsed_elements.append(
                            {
                                "source_id": parsed_element.source_id,
                                "element_type": parsed_element.element_type,
                                "sequence_index": parsed_element.sequence_index,
                                "page_number": parsed_element.page_number,
                                "heading_path": list(
                                    parsed_element.heading_path or ()
                                ),
                            }
                        )
                        if orm_element is not None:
                            parsed_to_persisted[parsed_element.source_id] = str(
                                orm_element.id
                            )
                except Exception as exc:  # noqa: BLE001 — mirror production
                    print(
                        f"    structure extraction failed for {doc.name}: "
                        f"{type(exc).__name__}"
                    )

            await replace_document_graph(db, document.id, _chunk_views(chunk_objects))

            summary[doc.name] = {
                "document_id": str(document.id),
                "chunk_ids": [str(c.id) for c in chunk_objects],
                "contents": contents,
                "parsed_elements": parsed_elements,
                "parsed_to_persisted": parsed_to_persisted,
            }

        await db.commit()

    return summary


async def load_persisted_elements(db: AsyncSession, user_id) -> list[dict]:
    """All persisted structure elements for the eval user, deterministic order."""
    from documents.models import Document
    from graph.models import DocumentStructureElement

    stmt = (
        select(
            DocumentStructureElement.id,
            DocumentStructureElement.document_id,
            DocumentStructureElement.element_type,
            DocumentStructureElement.sequence_index,
            DocumentStructureElement.page_number,
            DocumentStructureElement.heading_path,
            DocumentStructureElement.content,
            Document.name,
        )
        .join(Document, Document.id == DocumentStructureElement.document_id)
        .where(Document.user_id == uuid.UUID(str(user_id)))
        .order_by(
            Document.name,
            DocumentStructureElement.sequence_index,
            DocumentStructureElement.id,
        )
    )
    rows = (await db.execute(stmt)).fetchall()
    return [
        {
            "element_id": str(row.id),
            "document_id": str(row.document_id),
            "document_name": row.name,
            "element_type": row.element_type,
            "sequence_index": int(row.sequence_index),
            "page_number": row.page_number,
            "heading_path": list(row.heading_path or ()),
            "content": row.content or "",
        }
        for row in rows
    ]


